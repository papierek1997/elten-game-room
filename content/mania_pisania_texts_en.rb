The rain started just after breakfast. At first, there were little drops that could barely be heard against the window. Then the sky darkened, and water streamed down the street. Tom looked at the shoes he had set out for a walk. The shoes looked ready. He felt somewhat less so.

In the fridge he found a carrot, a stalk of celery, and two potatoes. There was a can of beans in the cupboard, with some pasta beside it. He decided that if he couldn't go for a long walk, he would make a big pot of soup. He had never made soup on his own before, but the list of things he needed seemed short.

He peeled the vegetables and placed them on a cutting board. He sliced the carrot into rounds, diced the potatoes, and cut the celery into shapes he couldn't name. It was all going into the pot anyway. He poured in water, turned on the stove, and went to get the salt.

At that very moment, someone knocked at the door. It was the neighbor from downstairs. She wanted to know whether Tom had a flashlight, because the light in her storage room had gone out. Tom lent her one and asked how long soup was supposed to cook.

“What kind of soup?”

“I don't know yet. So far, it's made of whatever I could find.”

The neighbor peered into the pot. She said it was a perfectly good start. She advised him to add the pasta later and the beans near the end. Tom wrote both tips on a piece of paper. In large letters he added, “Don't forget about the pot.”

Before the soup came to a boil, his sister called. She was going to stop by for a book on her way somewhere. Tom invited her for lunch as well. His sister promised to bring bread. When she arrived, she had a long loaf tucked under her arm and a wet umbrella. The umbrella stayed by the door, and the bread went onto the table.

The soup had been cooking for 20 minutes. Tom tasted it carefully. It was hot and had almost no flavor. He added some salt, a little pepper, and stirred again. His sister tasted it too and nodded. She said it could use some fresh parsley.

The neighbor returned with the flashlight. She brought parsley from a pot on her windowsill. Tom began to wonder whether everyone in the building could hear his conversations or whether rain simply encouraged soup-making. He set out a third plate.

They sat down at the table. It was still raining outside, but the kitchen was warm. The bread had a crunchy crust and the soup smelled of vegetables. The neighbor told them about the time she had added too much pasta to a pot. Instead of soup, she ended up with something you could cut with a knife.

Tom wrote down his recipe. He listed a quantity for every ingredient, though he wasn't sure about some of the numbers. At the end, he added three important things, rain outside the window, bread from his sister, and the neighbor with the parsley. His sister decided it would be hard to recreate the lunch without those extras.

In the afternoon, the sky grew brighter. Tom washed the pot and put on his shoes. He went out for a short walk. The air was fresh, and bright clouds were reflected in the puddles. When he returned, another bowl of soup was waiting for him. This time he knew exactly what to call it.
“I made soup for a rainy day,” he concluded.
