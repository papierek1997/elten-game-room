        'text' => <<~'TEXT'
On Saturday, Olivia woke up earlier than usual. The smell of wet grass drifted through the open window. It had rained during the night, but now the sun was already peeking over the neighbors' roof.

Her sweater lay on the chair, and two different slippers stood beside the bed. One belonged to Olivia, the other to Dad. Apparently, the cat had once again decided how the house should be arranged.

In the kitchen, Grandma was slicing bread and Grandpa was looking for his glasses. He checked his pockets, a drawer, and the windowsill. Only when he bent down to look under the table did his glasses slide from the top of his head straight onto his nose.

“Well, it’s a good thing I found them before breakfast,” he said. “Otherwise I might have mistaken the bread for a plank.”

After breakfast, everyone went out into the garden. The ground beneath the old apple tree was covered with fruit. Some apples had fallen during the night, others had been knocked down by the morning wind. Grandma brought three baskets. The first was for apples to make a pie, the second for juice, and the third for those that weren't worth saving for later.

Grandpa immediately decided that the third basket needed special attention. He sat beside it and began his quality inspection. He carefully examined each apple, turned it over in his hand, and then checked whether it tasted as good as the previous one.

Olivia watched him for a while.

“Grandpa, if you keep going like that, will there be anything left for lunch?”

Grandpa looked at the three baskets.

“Of course. The baskets.”

Before long, Mrs. Wilson appeared by the fence. She had come with an empty bowl to borrow some flour, but when she saw the apples, she remembered the apple pancakes her mother used to make. Apparently, they didn't need many ingredients. The most important things were a properly heated frying pan and enough patience not to flip the pancakes too soon.

Grandma invited her into the kitchen. Soon, laughter, the clatter of dishes, and the steady tapping of a spoon against a bowl could be heard from the house.

Olivia stayed in the garden and collected another 40 apples. She arranged them in neat rows to make them easier to count.

The cat looked at her work and apparently decided it was far too orderly. It walked right through the middle, nudged several apples aside, and then curled up in an empty basket without the slightest hint of remorse.

Olivia looked at the scattered fruit.

The cat looked at Olivia.

That was the end of the conversation.

At noon, a small table was set up beneath the apple tree. There were pancakes, a pitcher of water, and a plate piled with sliced apples. Grandpa brought chairs. One was a little wobbly, so he slid a piece of wood under the shorter leg.

Then he sat down on it carefully.

“You never know,” he said. “Some chairs are just waiting for you to let your guard down.”

They ate without hurrying. Mrs. Wilson talked about a vacation many years ago, Grandma kept adding pancakes to the plate, and Olivia listened to the birds hidden somewhere high among the branches.

Only the cat had no time to rest. It lay in the basket on Olivia's sweater, which had apparently just been promoted to a blanket, and made sure nobody got the idea of putting apples in there.

In the evening, Olivia went back to the garden for her sweater. One apple remained in the grass. She picked it up, wiped it on her sleeve, and sat down under the tree.

Warm light glowed in the windows. The smell of apple pie baking drifted from the kitchen, and after the long day the garden had grown quiet.

Olivia bit into the apple and thought that, really, it didn't take much for a day to turn out well.

Sometimes all you need is two mismatched slippers, a little rain at night, and a breakfast at which someone almost mistakes bread for a plank.
