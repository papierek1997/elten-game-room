Jake found the box at the very back of the closet while helping his parents clear out his old room.
It was gray, slightly dented, and had a crooked label stuck to it that read “Tomorrow.”
He stared at it for a moment, trying to remember what it was about. Then he remembered all too well.
When he was ten, he put everything he intended to deal with later into this box. He didn't throw things away, fix them, or put them where they belonged. He simply postponed them until tomorrow.
He opened the lid.
Eight buttons lay on top.
“Of course,” he muttered under his breath.
Under the buttons he found a few drawings, an old bag strap, an envelope, crayons without their paper wrappers, and a wooden dog with three legs.
The fourth leg lay beside it.
He remembered the dog immediately. Grandpa had given it to him. He used to carry it everywhere until one day the toy fell off a table and lost a leg.
Jake had meant to glue it back on the next day.
Almost twenty years had passed.
He carried the dog into the kitchen.
Mom was sitting at the table, peeling potatoes.
“Do we have any wood glue somewhere?”
She looked first at the dog, then at Jake.
“I see tomorrow has finally arrived.”
The glue was still in the same drawer, although the drawer had changed color three times since then. Jake applied a little (glue, not drawer) to the wooden leg, held it in place for a moment, and put the dog on the windowsill.
He returned to the box and took out the envelope.
It was addressed to Aunt Hannah. Inside was an unfinished letter.
He had written just one sentence.
“The trip to the river was fun, and I already have 12 stones.”
The rest of the page was blank.
Jake laughed. Aunt Hannah had lived in another city for years, so they mostly exchanged text messages and occasionally called each other.
He took out his phone, photographed the unfinished letter, and sent it to her with a note.
“Sorry for the slight delay in replying. I don't collect stones anymore.”
A reply buzzed in a minute later.
“That's a shame. I had a very nice pebble to trade with you.”
Under the letter was the strap from a navy-blue bag. Jake remembered that too. For several weeks he had carried books under his arm because the strap had broken, and repairing it had seemed to require specialized knowledge and probably tools from NASA.
Now he examined the buckle.
All he had to do was thread the strap through the metal clasp.
It took him perhaps twenty seconds.
“Impossible,” he whispered.
At the bottom were the drawings. A car with six wheels, a house with three chimneys, and something that might have been a dragon or an exceptionally angry chicken.
And one more drawing.
It showed the wooden dog standing beside a boy. Both had very long legs.
Jake took the sheet into the kitchen and put it next to the repaired toy.
Mom examined the picture.
“The dog looks quite like him.”
“And the boy?”
“A bit too tall.”
At the very bottom of the box he found a small brass bell.
He didn't remember it at all.
He rang it once.
Mom leaned out of the kitchen.
“Don't start!”
“Start what?”
“You once walked around the house with that thing for half a day.”
“Really?”
“You claimed you were checking where it sounded best.”
Jake rang it again.
“And where did it sound best?”
“The same everywhere.”
He put the bell on the table.
A few hours later, the room looked different. Some things went into boxes to take home, some into boxes of things to donate, and others into the trash.
The gray box was empty.
Jake sat on the floor and looked at the old label.
“Tomorrow.”
He peeled it off carefully.
For a moment he wondered whether to write “Done” in its place.
Or perhaps “At last”?
“But that would be like scolding myself.”
In the end, he wrote nothing.
He took the wooden dog home with him. Later, he placed it on the shelf above his desk. It wobbled a little, but stood on all four legs.
The empty box stayed at his parents' house.
That evening, Mom sent him a photo of the cat sleeping inside it.
Under the picture she wrote only this.
“Whiskers has found a use for it.”
“Faster than I did,” he replied.
