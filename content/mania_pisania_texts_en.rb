        'text' => <<~'TEXT'
Megan noticed the basket before she even sat down.

It stood beneath the seat across from her, covered with a red-striped kitchen towel. The towel moved once, then again.

Megan pushed her backpack under her seat.

“A hen?”

The older man sitting by the window looked up from his book.

“Everyone asks if it's a hen.”

He lifted a corner of the cloth.

Inside lay a small dog with brown ears. It was curled up so tightly that the basket looked as though it had been made just for him.

“Disappointed?”

“A little. A hen would have been more interesting.”

The dog opened one eye.

“Hear that?” the man said. “You’re not impressing anyone.”

The train pulled away.

Megan was returning from visiting her sister. They had planned to spend three days together and do at least five things they had written down in their messages. They went for one walk. They spent the rest of the time sitting in the kitchen.

She didn't consider it a failure.

Outside the window came warehouses, then community gardens, then fields. Megan watched for a while, but soon the landscape began to look like the same view scrolling past over and over again.

The older man closed his book.

“Are you going far?”

“I’ve still got a way to go,” Megan said.

Mr. Anderson, as he introduced himself, was getting off two stops before Megan. He was going to his granddaughter's birthday party.

“Is the dog invited too?”

“The dog is the main attraction. I'm just bringing a present.”

He pulled a paper bag out from under the seat.

“I made it myself.”

For a moment Megan imagined a wooden horse, a bird feeder, or something equally ambitious.

The scarf, displayed in all its glory, was red, very long, and noticeably wider at one end than the other.

“It’s my first attempt,” he explained.

“I can tell.”

“You're very direct.”

“My sister says that too.”

She took a roll from her backpack. They had bought six that morning at the bakery near her sister's home, although they both knew Megan didn't need six rolls for the journey.

“You’ve got enough provisions for an evacuation,” Mr. Anderson observed, eyeing the baked goods.

“My sister thinks people get hungry the moment they board a train.”

“A wise woman.”

She gave him one.

The dog immediately stopped dozing.

“You're not getting any, Buddy.”

The dog stared.

“That doesn’t work on me,” Mr. Anderson told himself firmly and calmly.

The dog kept staring.

“Please don't look, or he'll see he has public support.”

Megan turned toward the window.
Meanwhile, the dog tried every trick he knew to catch the older man's attention.
“Oh, all right, let him have something,” he said with a sigh, taking a small dog treat from his pocket.

“And that is how authority collapses.”

They ate in silence for a few minutes.

Then conversation started up again on its own. About his granddaughter, Megan's sister, and the chair in her kitchen that had squeaked for two years while she kept putting off fixing it.

“You need to tighten it.”

“We did.”

“Everything?”

“Everything that looked like it could be tightened.”

“And?”

“Now it squeaks in a higher pitch.”

The older man nodded as though this was entirely consistent with his experience.

When the loudspeaker announced his station, he began gathering his things.

Book, bag, scarf, basket.

The dog poked his muzzle out from under the towel and watched the commotion.

“Does he know where to get off?”

“He thinks we get off everywhere.”

A girl in a green jacket waited on the platform.
“Buddy! Grandpa!” she shouted happily.

“Well, that’s just lovely,” the man said. “Seventy years of life, and I lose to someone who eats off the floor.”

The girl rushed up and hugged him so tightly that the paper bag holding the scarf folded in half.

The doors closed, and Megan waved to them through the window.

The train moved on.

A tiny strand of red yarn was left on the opposite seat.

Megan picked it up and turned it between her fingers for a moment.

Then she slipped it into her jacket pocket.

She wasn't quite sure why.
