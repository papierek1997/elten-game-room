On the fourth floor, beside a window, stood a small table. Everyone used it. Sometimes there was a newspaper on it, sometimes a letter, and sometimes a bag of apples for a neighbor. One Monday, a note appeared there that read, “Things someone might find useful.”
Mrs. Evans came first. She left two mugs because she had too many in her cupboard. One was white, the other had yellow polka dots. She put a clean cloth under the mugs so they wouldn't scratch the table. By the afternoon, the mugs were gone. In their place was a book about gardening.
Mr. Adams took the book. He lived on the first floor and had a small patch of soil beneath his window. He had wanted to plant flowers there for a long time. A few days later, he left a packet of seeds on the table. He added a note saying that all they needed was sunshine, water, and a little patience.
Will from apartment number 7 decided that patience might be the difficult part. He wanted to see a flower right away, preferably. He took a few seeds, filled a pot with soil, and put it on the windowsill. On the first day, he checked it every hour.
On the second day, he only looked in the morning and evening. On the third day, he forgot in the morning but ran straight to the window after school. The soil still looked the same.
Mr. Adams told him that a plant does its work underground first.
Will crouched beside the pot and studied the soil for a moment.
“It could work a little faster,” he decided.
Meanwhile, the table filled up with odds and ends. There were pencils, a box of crayons, a scarf, and a little lamp. Someone even left a single sock. Mrs. Evans put up a new note asking that socks arrive in pairs. The next day, a second sock appeared. Nobody admitted to owning either one.
On Friday, Will saw a green leaf. It was small and slightly bent, but it had definitely grown out of the soil. The boy called his mother, then Mr. Adams, and finally Mrs. Evans. Everyone came to see the plant.
Mr. Adams said the hardest part now would be not watering it every five minutes.
On Saturday, the neighbors gathered in front of the building. They brought a trowel, a rake, and a bucket. They planted flowers beneath Mr. Adams's window. Will measured the spacing for the seedlings, Mrs. Evans handed out the plants, and Will's mother carried water.
The work went slowly. First someone brought a bucket that was too small, then Mr. Adams spent several minutes searching for the trowel he was holding in his hand the whole time. Will decided that, at this rate, the flowers would bloom before they finished planting them.
When they finally finished, they sat on a bench. Someone brought tea, someone else brought a cake. The yellow polka-dot mug reappeared. It was now in the hands of a neighbor from the third floor. She admitted she'd been using it every day since Monday and probably wouldn't part with it now.
In the evening, the table on the fourth floor was almost empty. Only a pencil and a new note lay on it. Will had written, “If you need something, ask.” He drew a little flower underneath. It wasn't a perfect drawing, but everyone knew what it showed.
From then on, people still left things on the table, but the neighbors knocked on one another's doors more often. Sometimes they needed sugar or a screwdriver, and sometimes they simply wanted to chat for a while.
The plants beneath the window grew. Will still checked his flowerpot every day, but no longer every hour.
