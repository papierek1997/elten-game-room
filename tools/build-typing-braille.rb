# Build-time only. Preserve the supplied Polish files; resolve all new includes
# from the pinned Liblouis release, keeping original bytes and licence headers.
require 'base64'
require 'zlib'
require 'digest'
require_relative '../lib/mania_pisania/braille_catalog'
require_relative '../content/mania_pisania_braille_tables'
abort 'Usage: ruby tools/build-typing-braille.rb LIBLOUIS_TABLE_DIRECTORY' unless ARGV.length == 1
root = File.expand_path(ARGV.fetch(0))
originals = GameRoomTyping::BrailleTableData::FILES.to_h do |name, (_, encoded)|
  [name, Zlib::Inflate.inflate(Base64.strict_decode64(encoded))]
end
files = {}
visit = lambda do |name|
  raise "Invalid table dependency #{name}" unless File.basename(name) == name
  return if files.key?(name)
  files[name] = originals[name] || File.binread(File.join(root, name))
  files[name].dup.force_encoding('UTF-8').scan(/^\s*include\s+([^\s#]+)/).flatten.each do |names|
    names.split(',').each { |dependency| visit.call(dependency) }
  end
end
GameRoomTyping::BrailleCatalog::FILES.each_value { |name| visit.call(name) }
originals.each { |name, bytes| files[name] = bytes if name.end_with?('.dll') }
checksum = Digest::SHA256.hexdigest(files.sort.map { |name, data| name + Digest::SHA256.hexdigest(data) }.join)
rows = files.sort.map { |name, data| "      #{name.dump} => [#{Digest::SHA256.hexdigest(data).dump}, #{Base64.strict_encode64(Zlib::Deflate.deflate(data)).dump}]" }
File.binwrite(File.expand_path('../content/mania_pisania_braille_tables.rb', __dir__), <<~RUBY)
  # Generated by tools/build-typing-braille.rb from Liblouis 3.39.0 and the author's Polish tables.
  # LGPL-2.1-or-later; original headers are embedded. See THIRD_PARTY_NOTICES.md.
  module GameRoomTyping
    module BrailleTableData
      CHECKSUM = #{checksum.dump}
      FILES = {
  #{rows.join(",\n")}
      }.freeze
    end
  end
RUBY
puts "Embedded #{files.length} files for #{GameRoomTyping::BrailleCatalog::FILES.length} selectable tables"
