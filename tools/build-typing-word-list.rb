# Builds a runtime pack from a UTF-8, one-word-per-line list.
# Keep plain exports outside runtime; only 3..12-letter words are drawn.
require 'base64'
require 'digest'
require 'json'
require 'zlib'
require_relative 'support/output_set'
abort 'Usage: ruby tools/build-typing-word-list.rb LANGUAGE EXPORTED_TXT SORTED_TXT' unless ARGV.length == 3
language, source, target = ARGV
abort 'Supported packs: en pl cs es ru' unless %w[en pl cs es ru].include?(language)
all = File.readlines(source, encoding: 'UTF-8', chomp: true).map(&:strip).reject(&:empty?).uniq.sort
raise 'Invalid UTF-8 word' unless all.all?(&:valid_encoding?)
full_export = all.join("\n") + "\n"
words = all.select { |word| word.length.between?(3, 12) && word.match?(/\A[\p{Latin}\p{Cyrillic}]+\z/) }
raise 'Empty word pack' if words.empty?
checksum = Digest::SHA256.hexdigest(words.join("\n") + "\n")
blocks = words.each_slice(2048).map do |slice|
  bytes = slice.join("\n") + "\n"
  raise 'Oversized word block' if bytes.bytesize > 131_072
  Base64.strict_encode64(Zlib::Deflate.deflate(bytes))
end
runtime_path = File.expand_path("../content/mania_pisania_words_#{language}.rb", __dir__)
runtime_content = <<~RUBY
  # encoding: UTF-8
  # Generated by tools/build-typing-word-list.rb; see content/mania_pisania_words_SOURCES.md.
  module GameRoomTyping
    module WordData#{language.upcase}
      CHECKSUM = #{checksum.dump}.freeze
      COUNT = #{words.length}
      BLOCKS = %w[
  #{blocks.map { |block| '      ' + block }.join("\n")}
      ].freeze
    end
  end
RUBY
GameRoomToolOutputs.commit({target => full_export, runtime_path => runtime_content}, label: 'Typing word list')
puts JSON.generate(language: language, complete_forms: all.length, playable_words: words.length,
  full_list_sha256: Digest::SHA256.hexdigest(full_export), checksum: checksum)
